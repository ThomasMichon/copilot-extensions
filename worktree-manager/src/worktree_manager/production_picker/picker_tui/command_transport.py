"""Literal argv transport for contributed plugin commands."""

from __future__ import annotations

import os
import json
import shutil
from collections.abc import Sequence
from pathlib import Path

from ... import picker_review
from ...engine_environment import _engine_environment

_CHILD_ENV_UNSET = (
    "COPILOT_EXTENSIONS_CONTEXT",
    "COPILOT_PLUGIN_INSTALL_STAGED",
    "COPILOT_PLUGIN_ROOT",
    "COPILOT_PLUGIN_STAGED_FROM",
    "PYTHONPATH",
)


def child_process_env() -> dict[str, str]:
    """Remove parent-plugin identity before crossing a contributed CLI boundary."""
    env = _engine_environment()
    for key in _CHILD_ENV_UNSET:
        env.pop(key, None)
    if picker_review.active():
        env["AGENT_DISPATCH_NO_AUTOSTART"] = "1"
        env["PYTHONDONTWRITEBYTECODE"] = "1"
    return env


def parse_action_json(raw):
    text = str(raw or "").strip()
    if not text:
        raise ValueError("embody did not print JSON")
    start = text.find("{")
    if start < 0:
        raise ValueError("embody did not print JSON")
    return json.loads(text[start:])


def command_result(proc, *, preserve_output: bool = False) -> tuple[bool, str]:
    if preserve_output:
        parts = [(proc.stdout or "").strip()]
        if proc.stderr:
            parts.append("stderr:\n" + proc.stderr.strip())
        if proc.returncode:
            parts.append(f"exit {proc.returncode}")
        return proc.returncode == 0, "\n\n".join(part for part in parts if part)
    if proc.returncode:
        detail = (proc.stderr or "").strip().splitlines()
        return False, (detail[-1] if detail else f"exit {proc.returncode}")[:200]
    return True, (proc.stdout or "").strip()[:200]


def resolve_command(command_argv: Sequence[str]) -> list[str]:
    """Resolve a command without reinterpreting already-substituted form values."""
    argv = list(command_argv)
    if argv:
        resolved = shutil.which(argv[0])
        if resolved:
            argv = [resolved, *argv[1:]]
    if os.name == "nt" and argv and Path(argv[0]).suffix.casefold() == ".cmd":
        command = Path(argv[0])
        marker = "Generated by libs/payload-invocation/generate.py."
        with command.open("rb") as source:
            encoded_marker = marker.encode("ascii")
            generated = encoded_marker in source.readline() or encoded_marker in source.readline()
        if generated:
            script = command.with_suffix(".ps1")
            if (
                not script.is_file()
                or command.is_symlink()
                or script.is_symlink()
                or command.resolve().parent != script.resolve().parent
                or command.resolve().stem.casefold() != script.resolve().stem.casefold()
            ):
                raise OSError(f"generated command has no matching PowerShell sibling: {command}")
            try:
                with script.open(encoding="utf-8") as source:
                    matching = marker in source.readline()
            except UnicodeError as exc:
                raise OSError(f"cannot inspect PowerShell launcher {script}") from exc
            if not matching:
                raise OSError(f"PowerShell sibling is not a generated payload launcher: {script}")
            host = shutil.which("pwsh")
            needs_verbatim = any(
                not value or any(char in value for char in '"\r\n&|<>%^!()')
                for value in argv[1:]
            )
            if needs_verbatim and not host:
                raise OSError("PowerShell 7 (pwsh) is required to preserve form argument values")
            if host:
                # A batch hop strips JSON quotes and splits multiline form values.
                argv = [
                    host, "-NoProfile", "-ExecutionPolicy", "Bypass", "-File",
                    str(script), *argv[1:],
                ]
    return argv
