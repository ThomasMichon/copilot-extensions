def test_missing_pwsh_preserves_legacy_simple_command_but_rejects_lossy_values(
    tmp_path, monkeypatch,
):
    command, _ = _launchers(tmp_path)
    _windows(monkeypatch, command, host=None)
    assert tasks._resolve_command(["fixture", "--version"]) == [str(command), "--version"]
    for value in ('{"literal":1}', "", "one\ntwo", "a&b", "%PATH%", "^!", "(value)"):
        ok, message = _runtime(command).run_resolved(["fixture", value])
        assert not ok
        assert "PowerShell 7" in message


@pytest.mark.parametrize("problem", ["missing", "foreign", "unreadable"])
def test_launcher_failure_is_a_terminal_action_and_list_error(tmp_path, monkeypatch, problem):
    command, script = _launchers(tmp_path)
    _windows(monkeypatch, command)
    if problem == "missing":
        script.unlink()
    elif problem == "foreign":
        script.write_text("# unrelated script\n", encoding="utf-8")
    else:
        real_open = Path.open

        def fail_open(path, *args, **kwargs):
            if path == command:
                raise PermissionError("launcher metadata unreadable")
            return real_open(path, *args, **kwargs)

        monkeypatch.setattr(Path, "open", fail_open)
    runtime = _runtime(command)
    ok, message = runtime.run_resolved(["fixture", '{"literal":1}'])
    assert not ok and message
    state, rows, error, summary = runtime._exec_list({})
    assert state == "error" and rows == [] and error and summary == {}
    runtime._inflight.add("local")
    runtime._run_list_stream("local", {})
    assert runtime.get("local")[0] == "error"
    assert "local" not in runtime._inflight


def test_generated_sibling_reparse_cannot_redirect_transport(tmp_path, monkeypatch):
    command, script = _launchers(tmp_path)
    _windows(monkeypatch, command)
    real_resolve = Path.resolve

    def redirect(path, *args, **kwargs):
        if path == script:
            return tmp_path / "elsewhere" / script.name
        return real_resolve(path, *args, **kwargs)

    monkeypatch.setattr(Path, "resolve", redirect)
    with pytest.raises(OSError, match="matching PowerShell sibling"):
        tasks._resolve_command(["fixture", "value"])


