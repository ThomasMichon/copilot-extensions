MARKER = "Generated by libs/payload-invocation/generate.py."


def _launchers(tmp_path):
    command = tmp_path / "fixture.cmd"
    command.write_text(f"@echo off\nrem {MARKER} Do not edit.\n", encoding="utf-8")
    script = command.with_suffix(".ps1")
    script.write_text(
        f"# {MARKER} Do not edit.\n"
        "[Console]::WriteLine((ConvertTo-Json -InputObject @($args) -Compress))\n",
        encoding="utf-8",
    )
    return command, script


def _windows(monkeypatch, command, host="fixture-pwsh"):
    monkeypatch.setattr(command_transport, "os", SimpleNamespace(name="nt", environ=os.environ))
    monkeypatch.setattr(
        command_transport.shutil, "which",
        lambda name: host if name == "pwsh" else str(command) if name == "fixture" else None,
    )


def _runtime(command):
    pivot = pivots.parse_manifest(
        {"label": "Fixture", "list": [str(command)],
         "entry": {"id": "id", "title": "title"}},
        name="fixture", source_path=str(command),
    )
    return tasks.RegisteredPivotRuntime(pivot)


def test_generated_command_resolves_direct_sibling_without_reformatting(tmp_path, monkeypatch):
    command, script = _launchers(tmp_path)
    _windows(monkeypatch, command)
    values = ['{"label":"{machine}"}', "line one\nline two", "", "a&b|c<d>%e^!()", " spaced "]
    assert tasks._resolve_command(["fixture", *values]) == [
        "fixture-pwsh", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File",
        str(script), *values,
    ]
    assert tasks._resolve_argv(["fixture", "{value}"], {"value": values[0]})[-1] == values[0]


@pytest.mark.parametrize("windows", [True, False])
def test_non_sdk_command_keeps_existing_transport(tmp_path, monkeypatch, windows):
    command, _script = _launchers(tmp_path)
    command.write_text("@echo off\nrem unrelated wrapper\n", encoding="utf-8")
    _windows(monkeypatch, command)
    if not windows:
        monkeypatch.setattr(command_transport, "os", SimpleNamespace(name="posix", environ=os.environ))
    assert tasks._resolve_command(["fixture", '{"literal":1}']) == [
        str(command), '{"literal":1}',
    ]


