@pytest.mark.skipif(
    os.name != "nt" or not all(os.environ.get(key) for key in (
        "TEST_INSTALLED_DISPATCH_LAUNCHER", "TEST_INSTALLED_USERPROFILE",
    )),
    reason="opt-in native installed Workers consumer",
)
def test_installed_workers_save_only_roundtrip(tmp_path, monkeypatch):
    command = os.environ["TEST_INSTALLED_DISPATCH_LAUNCHER"]
    registrar = tmp_path / "registrar"
    overrides = tmp_path / "overrides.json"
    # Read the existing installation, but never provision or publish a worker.
    monkeypatch.setenv("USERPROFILE", os.environ["TEST_INSTALLED_USERPROFILE"])
    monkeypatch.setenv("AGENT_DISPATCH_NO_SELFPROVISION", "1")
    monkeypatch.setenv("AGENT_DISPATCH_REGISTRAR_DIR", str(registrar))
    monkeypatch.setenv("AGENT_DISPATCH_REGISTRAR_DROPINS_DIR", str(tmp_path / "dropins"))
    monkeypatch.setenv("AGENT_DISPATCH_INSTALL_DIR", str(tmp_path / "install"))
    monkeypatch.setenv("AGENT_DISPATCH_OVERRIDES", str(overrides))
    runtime = _runtime(command)

    def invoke(*args):
        ok, receipt = runtime.run_resolved([command, *args], preserve_output=True)
        assert ok, receipt
        return json.loads(receipt)

    catalog = invoke("workers", "catalog")
    assert not catalog["summary"]["errors"], catalog["summary"]["errors"]
    template = next(row for row in catalog["entries"] if row["id"] == "template:worker-pool")
    assert not registrar.exists() and not overrides.exists()
    declaration = json.loads(next(
        field["default"] for field in template["fields"] if field["name"] == "declaration"
    ))
    declaration["description"] = 'Quoted "JSON", {machine}, line one\nline two & | < > %'
    declaration["labels"] = ["isolated-transport-proof"]
    fields = ("--field", "name=transport-proof", "--field",
              "declaration=" + json.dumps(declaration, indent=2), "--field", "repo_root=")
    saved = invoke(
        "workers", "save", template["id"], "--revision", template["revision"], *fields,
    )
    assert saved["persisted"] is True, saved
    draft = registrar / "worker-instances" / "transport-proof.json"
    stored = json.loads(draft.read_text(encoding="utf-8"))
    assert stored["configuration"]["declaration"] == {
        **declaration, "name": "transport-proof", "owner": "user-local:workers",
    }
    catalog = invoke("workers", "catalog")
    configured = next(row for row in catalog["entries"] if row["id"] == "instance:transport-proof")
    declaration["concurrency"] = 2
    edited = invoke(
        "workers", "save", configured["id"], "--revision", configured["revision"],
        "--field", "name=transport-proof", "--field",
        "declaration=" + json.dumps(declaration, indent=2), "--field", "repo_root=",
    )
    assert edited["persisted"] is True, edited
    revised = json.loads(draft.read_text(encoding="utf-8"))
    assert revised["id"] == stored["id"]
    assert revised["revision"] != stored["revision"]
    assert revised["configuration"]["declaration"] == {
        **declaration, "name": "transport-proof", "owner": "user-local:workers",
    }
    assert len(list(draft.parent.glob("*.json"))) == 1
    assert not (registrar / "worker-instances-active").exists()
    assert not (registrar / "pointers.json").exists()
    assert not overrides.exists()
