"""Both owner qualification and native identity must precede launcher retirement."""

from dataclasses import replace

import pytest

from agent_dispatch import launcher_replacement as subject
from agent_dispatch.supervisor_processes import WindowsProcess
from agent_procutil.process_retirement import RetirementRefused


@pytest.fixture
def conflict(tmp_path, monkeypatch):
    root = tmp_path
    (root / "current-version").write_text("incoming", encoding="utf-8")
    slot = root / "versions" / "outgoing"
    slot.mkdir(parents=True)
    launcher = root / "serve-service.ps1"
    launcher.write_text("# agent-dispatch coordinator launcher (generated by install.ps1)", encoding="utf-8")
    shell = r"C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe"
    holder = WindowsProcess(101, 1, shell, f'"{shell}" -NoProfile -File "{launcher}"', "100")
    python = str(slot / "Scripts" / "python.exe")
    central = WindowsProcess(102, 101, python, f'"{python}" -m agent_dispatch serve', "200")
    instance = {
        "state": "running", "service": "agent-dispatch-coordinator",
        "pid": "102", "birth": "windows:200",
        "source": str(slot / "Lib" / "site-packages" / "agent_dispatch" / "server.py"),
        "runtime_root": str(slot / "Lib" / "site-packages" / "agent_dispatch"),
    }
    census = [holder, central]
    instances = [instance]
    monkeypatch.setattr(subject, "launcher_holders", lambda _: {101: "windows:100"})
    monkeypatch.setattr(subject, "iter_windows_processes", lambda **_: list(census))
    monkeypatch.setattr(subject, "inspect_instances", lambda: instances)
    effects = []

    class Pin:
        def __init__(self, pid, birth):
            effects.append(("pin", pid, birth))
            self.pid = pid

        def __enter__(self):
            return self

        def __exit__(self, *_):
            effects.append(("close", self.pid))

        def pause(self, **_):
            effects.append(("pause", self.pid))

        def terminate(self, **_):
            effects.append(("terminate", self.pid))

    monkeypatch.setattr(subject, "PinnedProcess", Pin)
    return root, launcher, census, instances, effects


def retire(conflict):
    root, launcher, *_ = conflict
    return subject.retire_launcher_conflict(root, launcher, "incoming", "outgoing")


def test_only_actual_central_wrapper_holder_is_retired(conflict):
    _, _, census, _, effects = conflict
    census.append(WindowsProcess(103, 102, "worker.exe", "protected-session", "300"))
    assert retire(conflict) == {"retired": [101], "skipped": []}
    assert [event[1] for event in effects if event[0] == "terminate"] == [101]


def test_scheduled_wrapper_may_use_a_bare_executable_name(conflict):
    _, launcher, census, _, _ = conflict
    census[0] = replace(census[0], command_line=f'powershell.exe -NoProfile -File "{launcher}"')
    assert retire(conflict) == {"retired": [101], "skipped": []}


@pytest.mark.parametrize("header", [
    "# agent-dispatch-supervisor-launch-v1",
    "# agent-dispatch embody supervisor launcher (generated by install.ps1; legacy).",
])
def test_supervisor_current_and_legacy_first_lines_are_owned(conflict, header):
    root, old, census, instances, effects = conflict
    launcher = old.with_name("supervise-service.ps1")
    old.rename(launcher)
    launcher.write_text(header + "\nparam()\n")
    census[0] = replace(census[0], command_line=census[0].command_line.replace(str(old), str(launcher)))
    census[1] = replace(census[1], command_line=census[1].command_line.replace(
        "agent_dispatch serve", "agent_dispatch supervise serve",
    ))
    instances[0]["service"] = "agent-dispatch-supervisor"
    assert retire((root, launcher, census, instances, effects)) == {"retired": [101], "skipped": []}


@pytest.mark.parametrize("kind", [
    "foreign-root", "session-role", "lane-command", "reused-child", "reused-wrapper",
    "current-generation", "later-generation", "unknown-holder", "command-wrapper",
])
def test_foreign_or_unproved_holder_is_not_pinned(conflict, monkeypatch, kind):
    root, _, census, instances, effects = conflict
    if kind == "foreign-root":
        instances[0]["runtime_root"] = str(root.parent / "other-install")
    elif kind == "session-role":
        instances[0]["service"] = "agent-dispatch-session"
    elif kind == "lane-command":
        census[1] = replace(census[1], command_line=census[1].command_line.replace("serve", "supervise execute"))
    elif kind == "reused-child":
        instances[0]["birth"] = "windows:199"
    elif kind == "reused-wrapper":
        monkeypatch.setattr(subject, "launcher_holders", lambda _: {101: "windows:99"})
    elif kind in {"current-generation", "later-generation"}:
        generation = "incoming" if kind == "current-generation" else "future"
        for field in ("source", "runtime_root"):
            instances[0][field] = instances[0][field].replace("outgoing", generation)
    elif kind == "unknown-holder":
        monkeypatch.setattr(subject, "launcher_holders", lambda _: {999: "windows:99"})
    elif kind == "command-wrapper":
        census[0] = replace(census[0], command_line=census[0].command_line.replace("-File", "-Command"))
    assert retire(conflict)["retired"] == []
    assert effects == []


def test_reselection_at_effect_boundary_preserves_both_processes(conflict, monkeypatch):
    root, _, census, _, effects = conflict
    calls = 0

    def inventory(**_):
        nonlocal calls
        calls += 1
        if calls == 2:
            (root / "current-version").write_text("outgoing", encoding="utf-8")
        return list(census)

    monkeypatch.setattr(subject, "iter_windows_processes", inventory)
    assert retire(conflict)["retired"] == []
    assert not any(event[0] == "terminate" for event in effects)
    assert sum(event[0] == "close" for event in effects) == 2


def test_native_identity_pin_refusal_never_signals(conflict, monkeypatch):
    def refuse(*_):
        raise RetirementRefused("native birth mismatch")

    monkeypatch.setattr(subject, "PinnedProcess", refuse)
    assert retire(conflict)["retired"] == []
    assert conflict[-1] == []


def test_changed_holder_after_pin_is_not_terminated(conflict, monkeypatch):
    calls = 0

    def holders(_):
        nonlocal calls
        calls += 1
        return {101: "windows:100" if calls == 1 else "windows:999"}

    monkeypatch.setattr(subject, "launcher_holders", holders)
    assert retire(conflict)["retired"] == []
    assert not any(event[0] == "terminate" for event in conflict[-1])


@pytest.mark.parametrize("embedded_marker", [False, True])
def test_custom_launcher_is_not_a_retirement_authority(conflict, embedded_marker):
    content = "# custom operator launcher"
    if embedded_marker:
        content += "\n# agent-dispatch coordinator launcher (generated by install.ps1)"
    conflict[1].write_text(content, encoding="utf-8")
    with pytest.raises(RetirementRefused, match="custom launcher"):
        retire(conflict)
    assert conflict[-1] == []


def test_admitted_python_is_not_an_additional_file_holder_target(conflict, monkeypatch):
    monkeypatch.setattr(subject, "launcher_holders", lambda _: {102: "windows:200"})
    assert retire(conflict) == {"retired": [], "skipped": [102]}
    assert conflict[-1] == []
