pytestmark = pytest.mark.skipif(os.name != "nt", reason="Windows native file sharing")


def _quote(value) -> str:
    return "'" + str(value).replace("'", "''") + "'"


@pytest.mark.parametrize("host", ["powershell.exe", "pwsh"])
@pytest.mark.parametrize("role", ["coordinator", "supervisor"])
def test_installer_replaces_only_the_outgoing_central_holder(tmp_path, host, role):
    shell = shutil.which(host)
    assert shell, f"required Windows shell unavailable: {host}"
    root = tmp_path / "install"
    slot = root / "versions" / "outgoing"
    venv.EnvBuilder(with_pip=False).create(slot)
    packages = slot / "Lib" / "site-packages"
    (packages / "procutil.pth").write_text(
        str(Path(agent_procutil.__file__).resolve().parent.parent), encoding="utf-8",
    )
    package = packages / "agent_dispatch"
    package.mkdir()
    (package / "__init__.py").write_text("", encoding="utf-8")
    ready = root / "ready.json"
    (package / "__main__.py").write_text(
        "import json, os, subprocess, sys, time\n"
        "from pathlib import Path\n"
        "from agent_procutil.daemon_instances import admit_daemon_instance\n"
        "from agent_procutil._daemon_instance_identity import birth_identity\n"
        f"with admit_daemon_instance('agent-dispatch-{role}', source=__file__, purpose='production'):\n"
        "    worker = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(120)'],\n"
        "        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,\n"
        "        creationflags=subprocess.CREATE_NO_WINDOW)\n"
        f"    Path({str(ready)!r}).write_text(json.dumps({{\n"
        "        'central': [os.getpid(), birth_identity(os.getpid())],\n"
        "        'worker': [worker.pid, birth_identity(worker.pid)]}), encoding='utf-8')\n"
        "    time.sleep(120)\n",
        encoding="utf-8",
    )
    launcher = root / ("serve-service.ps1" if role == "coordinator" else "supervise-service.ps1")
    marker = "# agent-dispatch coordinator launcher (generated by install.ps1)"
    if role == "supervisor":
        generated = subprocess.run(
            [shell, "-NoProfile", "-NonInteractive", "-Command", f"""
$ErrorActionPreference='Stop'
$InstallDir={_quote(root)};$LinkDir={_quote(root / '.venv')}
$LinkPython={_quote(slot / 'Scripts' / 'python.exe')}
$utf8NoBom=[Text.UTF8Encoding]::new($false)
$script:GlobalActivationLockTimeoutSeconds=5
$tokens=$null;$errors=$null
$ast=[Management.Automation.Language.Parser]::ParseFile({_quote(INSTALLER)},[ref]$tokens,[ref]$errors)
if($errors.Count){{throw 'Installer parse failed'}}
$definitions=@($ast.FindAll({{param($node)
 $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -in @(
  'Enter-PluginSnapshotLock','Publish-FileAtomically','Publish-ServiceLauncher','Write-SupervisorLauncher')
}},$true))
if($definitions.Count -ne 4){{throw 'Supervisor construction owner is ambiguous'}}
foreach($function in $definitions){{ . ([scriptblock]::Create($function.Extent.Text)) }}
Write-SupervisorLauncher|Out-Null
"""],
            capture_output=True, text=True, timeout=30,
            creationflags=subprocess.CREATE_NO_WINDOW,
        )
        assert generated.returncode == 0, generated.stdout + generated.stderr
        marker = launcher.read_text(encoding="utf-8-sig").splitlines()[0]
    command = "serve" if role == "coordinator" else "supervise serve"
    launcher.write_text(
        marker + "\n"
        "$ErrorActionPreference='Stop'\n"
        "$hold=[IO.File]::Open($PSCommandPath,'Open','Read','Read')\n"
        f"try {{ & {_quote(slot / 'Scripts' / 'python.exe')} -m agent_dispatch {command} }}\n"
        "finally { $hold.Dispose() }\n",
        encoding="utf-8",
    )
    (root / "current-version").write_text("incoming", encoding="utf-8")
    preserved = root / "queue.db"
    preserved.write_bytes(b"existing application state")
    registry = tmp_path / "instances"
    identities = {}
    with daemon_test_lifecycle(owner="launcher-replacement-native", registry_root=registry) as context:
        env = dict(os.environ, **context, **{REGISTRY_ENV: str(registry)})
        wrapper = subprocess.Popen(
            [Path(shell).name, "-NoProfile", "-NonInteractive", "-File", str(launcher)],
            executable=shell,
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            env=env, creationflags=subprocess.CREATE_NO_WINDOW,
        )
        wrapper_birth = birth_identity(wrapper.pid)
        pins = ExitStack()
        try:
            deadline = time.monotonic() + 20
            while not ready.exists() and time.monotonic() < deadline and wrapper.poll() is None:
                time.sleep(.05)
            assert ready.exists(), f"central fixture did not admit; wrapper={wrapper.poll()}"
            identities = json.loads(ready.read_text(encoding="utf-8"))
            central = pins.enter_context(PinnedProcess(*identities["central"]))
            worker = pins.enter_context(PinnedProcess(*identities["worker"]))
            assert launcher_holders(launcher).get(wrapper.pid) == wrapper_birth
            script = f"""
$ErrorActionPreference='Stop'
$InstallDir={_quote(root)}
$VenvPython={_quote(sys.executable)}
$SrcVersion='incoming'
$script:ReplacedServiceGeneration='outgoing'
$script:GlobalActivationLockTimeoutSeconds=5
$tokens=$null;$errors=$null
$ast=[Management.Automation.Language.Parser]::ParseFile({_quote(INSTALLER)},[ref]$tokens,[ref]$errors)
if($errors.Count){{throw 'Installer parse failed'}}
$functions=@($ast.FindAll({{param($n)
    $n -is [Management.Automation.Language.FunctionDefinitionAst]
}},$true))
foreach($name in @('Enter-PluginSnapshotLock','Publish-FileAtomically','Publish-ServiceLauncher')){{
    $found=@($functions | Where-Object Name -eq $name)
    . ([scriptblock]::Create($found[0].Extent.Text))
}}
function Write-Warn {{ param($Message) Write-Output $Message }}
Publish-ServiceLauncher -Path {_quote(launcher)} -Content 'incoming-published'
"""
            result = subprocess.run(
                [shell, "-NoProfile", "-NonInteractive", "-Command", script],
                capture_output=True, text=True, timeout=50, env=env,
                creationflags=subprocess.CREATE_NO_WINDOW,
            )
            assert result.returncode == 0, result.stdout + result.stderr
            assert launcher.read_text(encoding="utf-8") == "incoming-published"
            assert preserved.read_bytes() == b"existing application state"
            wrapper.wait(timeout=5)
            assert not central.exited(), "non-holder central process was unnecessarily retired"
            assert not worker.exited(), "protected child was swept with its central parent"
        finally:
            for identity in identities.values():
                try:
                    with PinnedProcess(*identity) as process:
                        process.terminate(timeout=5)
                except ProcessLookupError:
                    pass
            if wrapper.poll() is None:
                wrapper.kill()
            wrapper.wait(timeout=5)
            pins.close()


@pytest.mark.parametrize("host", ["powershell.exe", "pwsh"])
def test_unrelated_self_held_reader_is_not_killed_or_reported_published(tmp_path, host):
    shell = shutil.which(host)
    assert shell, f"required Windows shell unavailable: {host}"
    launcher = tmp_path / "serve-service.ps1"
    launcher.write_text(
        "# agent-dispatch coordinator launcher (generated by install.ps1)\n",
        encoding="utf-8",
    )
    (tmp_path / "current-version").write_text("incoming", encoding="utf-8")
    (tmp_path / "versions" / "outgoing").mkdir(parents=True)
    script = f"""
$ErrorActionPreference='Stop'
$InstallDir={_quote(tmp_path)}
$VenvPython={_quote(sys.executable)}
$SrcVersion='incoming'
$script:ReplacedServiceGeneration='outgoing'
$script:GlobalActivationLockTimeoutSeconds=5
$tokens=$null;$errors=$null
$ast=[Management.Automation.Language.Parser]::ParseFile({_quote(INSTALLER)},[ref]$tokens,[ref]$errors)
$functions=@($ast.FindAll({{param($n)
    $n -is [Management.Automation.Language.FunctionDefinitionAst]
}},$true))
foreach($name in @('Enter-PluginSnapshotLock','Publish-FileAtomically','Publish-ServiceLauncher')){{
    $found=@($functions | Where-Object Name -eq $name)
    . ([scriptblock]::Create($found[0].Extent.Text))
}}
function Write-Warn {{ param($Message) Write-Output $Message }}
$original=[IO.File]::ReadAllText({_quote(launcher)})
$held=[IO.File]::Open({_quote(launcher)},'Open','Read','Read')
try {{
    $refused=$false
    try {{ Publish-ServiceLauncher -Path {_quote(launcher)} -Content 'must-not-publish' }}
    catch {{
        if(-not $_.Exception.Message.Contains({_quote(launcher)})){{throw 'Publication error omitted target'}}
        $refused=$true
    }}
    if(-not $refused){{throw 'Unpublished replacement reported success'}}
    if([IO.File]::ReadAllText({_quote(launcher)}) -cne $original){{throw 'Held reader damaged'}}
    Write-Output 'unrelated-holder-preserved publication-refused'
}} finally {{ $held.Dispose() }}
"""
    result = subprocess.run(
        [shell, "-NoProfile", "-NonInteractive", "-Command", script],
        capture_output=True, text=True, timeout=40,
        creationflags=subprocess.CREATE_NO_WINDOW,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert "unrelated-holder-preserved publication-refused" in result.stdout
